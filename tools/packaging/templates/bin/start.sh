#!/usr/bin/env bash
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
# shellcheck disable=SC1091
source "${ROOT}/util/env.sh"
# shellcheck disable=SC1091
source "${ROOT}/util/db-select.sh"

EMBEDDED_PY=""
for _py in python3.11 python3.10 python3.9; do
  if [[ -x "${HUE_BIN}/${_py}" ]]; then
    EMBEDDED_PY="${_py}"
    break
  fi
done
if [[ -z "${EMBEDDED_PY}" ]]; then
  echo "ERROR: embedded Python missing under ${HUE_BIN}/python3.{11,10,9}" >&2
  exit 1
fi
PY_XY="${EMBEDDED_PY#python}"
if [[ ! -d "${HUE_HOME}/lib/python-runtime/lib64/python${PY_XY}" ]]; then
  echo "ERROR: embedded Python stdlib missing at ${HUE_HOME}/lib/python-runtime" >&2
  echo "Please use a package built with embed-python.sh (stdlib + libpython)." >&2
  exit 1
fi

if [[ ! -e "${HUE_CLI}" ]]; then
  echo "ERROR: Hue CLI not found at ${HUE_CLI}" >&2
  exit 1
fi

if [[ -f "${HUE_RUN_DIR}/supervisor.pid" ]]; then
  old_pid="$(tr -d '[:space:]' < "${HUE_RUN_DIR}/supervisor.pid" || true)"
  if [[ -n "${old_pid}" ]] && kill -0 "${old_pid}" 2>/dev/null; then
    echo "Hue already running (pid ${old_pid})"
    exit 0
  fi
fi

packaging_ensure_sqlite

# Hue/Gunicorn default to OS user/group "hue". Map to the invoking account so
# root/start without a dedicated hue account still works.
RUN_USER="$(id -un)"
RUN_GROUP="$(id -gn)"
cat > "${HUE_CONF_DIR}/z-96-runtime-user.ini" <<EOF
# Auto-generated by bin/start.sh — do not edit by hand
[desktop]
server_user=${RUN_USER}
server_group=${RUN_GROUP}
EOF

echo "Migrating database..."
hue_run "${HUE_CLI}" migrate --noinput

USER_ARGS=(-u "${RUN_USER}" -g "${RUN_GROUP}")

echo "Starting Hue supervisor (daemon) as ${RUN_USER}:${RUN_GROUP}..."
hue_run "${SUPERVISOR_BIN}" -d \
  "${USER_ARGS[@]}" \
  -p "${HUE_RUN_DIR}/supervisor.pid" \
  -l "${DESKTOP_LOG_DIR}"

sleep 1
if [[ -f "${HUE_RUN_DIR}/supervisor.pid" ]]; then
  echo "Hue started. pid=$(tr -d '[:space:]' < "${HUE_RUN_DIR}/supervisor.pid")"
  echo "Logs: ${DESKTOP_LOG_DIR}"
  echo "UI default: http://0.0.0.0:8000  (see conf/z-10-defaults.ini)"
else
  echo "WARNING: supervisor.pid not found; check ${DESKTOP_LOG_DIR}" >&2
  exit 1
fi
